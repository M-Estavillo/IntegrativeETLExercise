const assert=require('node:assert/strict');
const fs=require('node:fs');
const {runETL,mapping}=require('./etl.js');
const texts=['source_A_SIS.csv','source_B_LMS.csv','source_C_Accounting.csv'].map(f=>fs.readFileSync(f,'utf8'));
const result=runETL(...texts);
assert.deepEqual(result.students.map(s=>s.studentId),[1001,1002,1003,1004,1006]);
assert.deepEqual(result.students[0],{studentId:1001,studentName:'Juan Dela Cruz',program:'Bachelor of Science in Information Technology',emailAddress:'juan.dc@example.com',courses:[{courseCode:'IT101',finalGrade:1.5,completionStatus:'Completed'}],accounting:{outstandingBalance:0,currency:'PHP'}});
assert.equal(result.students[1].courses[0].completionStatus,'Completed');
assert.equal(result.students[2].studentName,'Pedro Reyes');
assert.equal(result.students[2].accounting.outstandingBalance,1500);
assert.equal(result.students[3].program,'Bachelor of Science in Information Systems');
assert.deepEqual(result.students[3].courses,[]);
assert.equal(result.students[3].accounting.outstandingBalance,2500.5);
assert.equal(result.students[4].courses[0].finalGrade,'INC');
assert.equal(result.students[4].courses[0].completionStatus,'In Progress');
assert.equal(result.students[4].accounting,null);
assert.equal(result.warnings.length,4);
const multi=runETL(texts[0],texts[1]+'1001, it102 ,2.25, in progress\n',texts[2]);
assert.equal(multi.students[0].courses.length,2);
assert.equal(multi.students[0].courses[1].courseCode,'IT102');
assert.throws(()=>runETL(texts[0]+'1001,Duplicate,BSIT,a@b.com\n',texts[1],texts[2]),/Duplicate SIS/);
assert.throws(()=>runETL(texts[0],texts[1],texts[2]+'1001,0,PHP\n'),/Duplicate Accounting/);
assert.throws(()=>runETL(texts[0],texts[1]+'1001,IT101,2,Completed\n',texts[2]),/Duplicate LMS/);
assert.throws(()=>runETL(texts[0].replace('1001','1001x'),texts[1],texts[2]),/invalid student_id/);
assert.throws(()=>runETL(texts[0],texts[1],texts[2].replace('5000.00','bad')),/invalid decimal/);
assert.throws(()=>runETL('wrong\n1',texts[1],texts[2]),/missing columns/);
const blank=runETL(texts[0],texts[1].replace('1.50',''),texts[2].replace('5000.00',''));
assert.equal(blank.students[0].courses[0].finalGrade,null);
assert.equal(blank.students[1].accounting.outstandingBalance,null);
const empty=runETL(texts[0],texts[1].split('\n')[0],texts[2].split('\n')[0]);
assert.equal(empty.students.length,5);
assert(empty.students.every(s=>s.courses.length===0 && s.accounting===null));
const {parseCSV}=require('./csv-parser.js');
assert.deepEqual(parseCSV('\uFEFFa,b\r\n"comma, name","a""b\nline"\r\n'),[['a','b'],['comma, name','a"b\nline']]);
fs.writeFileSync('integrated_students.json',JSON.stringify(result.students,null,2)+'\n');
fs.writeFileSync('data-mapping.md','# Source-to-target data mapping\n\n| Source | Field | Target | Type | Rule |\n|---|---|---|---|---|\n'+mapping.map(row=>'| '+row.join(' | ')+' |').join('\n')+'\n');
console.log('PASS: all supplied records, mappings, missing data, unmatched IDs, INC, multiple courses, CSV quoting, duplicate and invalid input handling.');
